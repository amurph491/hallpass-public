package run.hallpass.application

import java.time.Instant
import run.hallpass.kernel.*
import cats.Monad
import cats.syntax.all.*

enum AgentEnrollmentRequestError:
  case InvalidLabel, InvalidExpiry

/** Safe human-management input. The plaintext credential is deliberately not an input to enrollment. */
final case class AgentCredentialEnrollmentRequest private (label: Option[String], expiresAt: Option[Instant])
object AgentCredentialEnrollmentRequest:
  def from(label: Option[String], expiresAt: Option[Instant]): Either[AgentEnrollmentRequestError, AgentCredentialEnrollmentRequest] =
    Either.cond(
      label.forall(validLabel),
      AgentCredentialEnrollmentRequest(label, expiresAt),
      AgentEnrollmentRequestError.InvalidLabel
    )

  private def validLabel(value: String): Boolean =
    value.nonEmpty && value.length <= 120 && value == value.trim && value.forall(character => !Character.isISOControl(character))

/** Safe persisted metadata. It has no plaintext credential field and cannot reproduce a one-time disclosure. */
final case class AgentCredentialMetadata(
    id: AgentCredentialId,
    agentId: AgentId,
    selector: AgentCredentialSelector,
    createdAt: Instant,
    expiresAt: Option[Instant],
    revokedAt: Option[Instant],
    lastUsedAt: Option[Instant],
    label: Option[String],
    issuedBy: Option[UserId]
)

/** Material generated by a dedicated crypto adapter before persistence. */
final class GeneratedAgentCredential private (
    val credentialId: AgentCredentialId,
    val credential: PresentedAgentCredential,
    val selector: AgentCredentialSelector,
    val verifier: StoredAgentCredentialVerifier,
    val verifierMetadata: CredentialVerifierMetadata
):
  override def toString: String =
    s"GeneratedAgentCredential(credentialId=$credentialId, selector=${selector.value}, credential=<redacted>, verifier=<redacted>)"

object GeneratedAgentCredential:
  private[hallpass] def issue(
      credentialId: AgentCredentialId,
      credential: PresentedAgentCredential,
      verifier: StoredAgentCredentialVerifier,
      verifierMetadata: CredentialVerifierMetadata
  ): GeneratedAgentCredential =
    new GeneratedAgentCredential(credentialId, credential, credential.selector, verifier, verifierMetadata)

/** The only result containing plaintext, intended for the one successful enrollment/rotation response. */
final class OneTimeAgentCredentialDisclosure private[hallpass] (
    val metadata: AgentCredentialMetadata,
    val credential: PresentedAgentCredential
):
  override def toString: String =
    s"OneTimeAgentCredentialDisclosure(metadata=$metadata, credential=<redacted>)"

enum AgentEnrollmentError:
  case InvalidRequest(reason: AgentEnrollmentRequestError)
  case AgentNotFound, ExistingActiveCredential, CredentialNotFound, PersistenceFailure

/** Cryptographic generation is outside the application core. It must use a CSPRNG and tenant-bound verification. */
trait AgentCredentialIssuer[F[_]]:
  def issue(tenant: TenantId): F[GeneratedAgentCredential]

/** Tenant-scoped enrollment lifecycle. Implementations make rotation revoke-and-create atomic. */
trait AgentCredentialEnrollmentRepository[F[_]]:
  def enroll(
      tenant: TenantId,
      agentId: AgentId,
      generated: GeneratedAgentCredential,
      request: AgentCredentialEnrollmentRequest,
      issuedBy: Principal.Human,
      at: Instant
  ): F[Either[AgentEnrollmentError, AgentCredentialMetadata]]

  def rotate(
      tenant: TenantId,
      agentId: AgentId,
      previousCredentialId: AgentCredentialId,
      generated: GeneratedAgentCredential,
      request: AgentCredentialEnrollmentRequest,
      issuedBy: Principal.Human,
      at: Instant
  ): F[Either[AgentEnrollmentError, AgentCredentialMetadata]]

  def revoke(
      tenant: TenantId,
      agentId: AgentId,
      credentialId: AgentCredentialId,
      at: Instant
  ): F[Either[AgentEnrollmentError, Unit]]

  def metadataFor(tenant: TenantId, agentId: AgentId): F[Vector[AgentCredentialMetadata]]

/** Application orchestration that discloses a generated credential only after its enrollment transaction succeeds.
  *
  * Every operation takes the authenticated human acting in a tenant, so the tenant comes from a current membership and
  * the issuing principal is recorded with the credential. */
final class AgentEnrollmentService[F[_]](
    credentials: AgentCredentialEnrollmentRepository[F],
    issuer: AgentCredentialIssuer[F]
)(using F: Monad[F]):
  def enroll(
      actor: AuthenticatedHuman,
      agentId: AgentId,
      request: AgentCredentialEnrollmentRequest,
      at: Instant
  ): F[Either[AgentEnrollmentError, OneTimeAgentCredentialDisclosure]] =
    validExpiry(request, at) match
      case Left(error) => F.pure(Left(error))
      case Right(_) =>
        issuer.issue(actor.tenant).flatMap: generated =>
          credentials.enroll(actor.tenant, agentId, generated, request, actor.principal, at).map:
            case Right(metadata) => Right(OneTimeAgentCredentialDisclosure(metadata, generated.credential))
            case Left(error)     => Left(error)

  def rotate(
      actor: AuthenticatedHuman,
      agentId: AgentId,
      previousCredentialId: AgentCredentialId,
      request: AgentCredentialEnrollmentRequest,
      at: Instant
  ): F[Either[AgentEnrollmentError, OneTimeAgentCredentialDisclosure]] =
    validExpiry(request, at) match
      case Left(error) => F.pure(Left(error))
      case Right(_) =>
        issuer.issue(actor.tenant).flatMap: generated =>
          credentials.rotate(actor.tenant, agentId, previousCredentialId, generated, request, actor.principal, at).map:
            case Right(metadata) => Right(OneTimeAgentCredentialDisclosure(metadata, generated.credential))
            case Left(error)     => Left(error)

  def revoke(
      actor: AuthenticatedHuman,
      agentId: AgentId,
      credentialId: AgentCredentialId,
      at: Instant
  ): F[Either[AgentEnrollmentError, Unit]] =
    credentials.revoke(actor.tenant, agentId, credentialId, at)

  def metadataFor(actor: AuthenticatedHuman, agentId: AgentId): F[Vector[AgentCredentialMetadata]] =
    credentials.metadataFor(actor.tenant, agentId)

  private def validExpiry(
      request: AgentCredentialEnrollmentRequest,
      at: Instant
  ): Either[AgentEnrollmentError, Unit] =
    Either.cond(
      request.expiresAt.forall(_.isAfter(at)),
      (),
      AgentEnrollmentError.InvalidRequest(AgentEnrollmentRequestError.InvalidExpiry)
    )
